    fun text(source: String, english: Boolean): String = if (english) translate(source, 0) else translateChinese(source)

    private fun translateChinese(source: String): String {
        chinese[source]?.let { return it }
        if (source.contains('\n')) return source.split('\n').joinToString("\n") { translateChinese(it) }
        Regex("^(.*)/(.*) OK$").matchEntire(source)?.let { return "${it.groupValues[1]}/${it.groupValues[2]} 通过" }
        // Debug flags and reference-source codes are display values, not translated storage keys.
        if (source.contains(", ")) return source.split(", ").joinToString(", ") { translateChinese(it) }
        Regex("^Pose ([0-9]+(?:[.,][0-9]+)?)$").matchEntire(source)?.let { return "姿态 ${it.groupValues[1]}" }
        val colon = source.indexOf('：')
        if (colon >= 0 && colon + 1 < source.length) return source.substring(0, colon + 1) + translateChinese(source.substring(colon + 1))
        return source
    }

    private fun translate(source: String, depth: Int): String {
        if (depth > 5) return source
        exact[source]?.let { return it }
        // Duration values are generated from locale-independent internal Chinese unit labels.
        Regex("^([0-9]+(?:[.,][0-9]+)?) (小时|天)$").matchEntire(source)?.let { match ->
            val number = match.groupValues[1]
            val singular = number.replace(',', '.').toDoubleOrNull() == 1.0
            val unit = if (match.groupValues[2] == "小时") {
                if (singular) "hour" else "hours"
            } else if (singular) "day" else "days"
            return "$number $unit"
        }
        if (source.startsWith("ONNX部署包 ")) return "ONNX deployment bundle " + source.removePrefix("ONNX部署包 ")
        // Composed status values and newline-separated self-check results need leaf translation.
        if (source.contains('\n')) return source.split('\n').joinToString("\n") { translate(it, depth + 1) }
        Regex("^([A-Za-z0-9_]+) 增益：(.*)$").matchEntire(source)?.let { match ->
            return "${match.groupValues[1]} gain: ${match.groupValues[2]}"
        }
        templates.forEach { template ->
            val match = template.regex.matchEntire(source) ?: return@forEach
            return template.pieces.joinToString("") { piece ->
                if (piece is Int) translate(match.groupValues[piece + 1], depth + 1) else piece.toString()
            }
        }
        if (source.contains(" · ")) return source.split(" · ").joinToString(" · ") { translate(it, depth + 1) }
        if (source.contains(", ")) return source.split(", ").joinToString(", ") { translate(it, depth + 1) }
        return source
    }
